#!/usr/bin/env python3
"""Package a game's dmhost and data pack into a runnable Linux folder.

The output folder gets:
  - every file of the data pack, hard-linked (copied only across devices)
  - bin/dmhost (a copy of the built host binary)
  - save/ and temp/ (empty)
  - an executable bash launcher named after --app
  - game.json, in the format the Nova menu reads

Usage:
  python3 devtools/linux_package.py --game TITLEID --data DATA_DIR --out OUT_DIR \
      --title "Name" --app short_id [--host PATH_TO_DMHOST]
"""

import argparse
import errno
import json
import os
import re
import shutil
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

TITLEID_RE = re.compile(r"^[0-9A-Fa-f]{16}$")
APP_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")

LAUNCHER_TEMPLATE = """#!/bin/bash
# Launcher for {title}, generated by devtools/linux_package.py.
set -eu
D="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
export DM_ROOT="$D"
export DM_ROMFS="$D/RomFS"
export DM_SAVE="$D/save"
export DM_TEMP="$D/temp"
export DM_VK_SHADERS="$D/shaders.dmsv"

ENV_FILE="$D/env.txt"
if [ -f "$ENV_FILE" ]; then
  while IFS= read -r line || [ -n "$line" ]; do
    line="${{line%$'\\r'}}"
    case "$line" in ''|'#'*) continue ;; esac
    case "$line" in *=*) ;; *) continue ;; esac
    key="${{line%%=*}}"
    val="${{line#*=}}"
    [[ "$key" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]] || continue
    if [ "$key" = DM_SHARED_FONT_EXT ]; then
      val="$D/nintendo_ext.ttf"
    else
      case "$val" in */sdcard*) continue ;; esac
    fi
    export "$key=$val"
  done < "$ENV_FILE"
fi

cd "$D"
exec "$D/bin/dmhost" mods
"""


def fail(message):
    print(f"error: {message}", file=sys.stderr)
    sys.exit(1)


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--game", required=True, help="16-hex title ID")
    parser.add_argument("--data", required=True, type=Path, help="data pack folder")
    parser.add_argument("--out", required=True, type=Path, help="output folder")
    parser.add_argument("--title", required=True, help="title shown in the menu")
    parser.add_argument("--app", required=True, help="short id, e.g. burnout")
    parser.add_argument(
        "--host",
        type=Path,
        help="path to dmhost (default: nxnative/dm/linux/out/<TITLEID>/dmhost)",
    )
    parser.add_argument(
        "--logo",
        type=Path,
        help="logo.png source for the menu icon (default: <data>/logo.png if present)",
    )
    return parser.parse_args()


def link_or_copy(src, dst, counts, warned):
    if dst.is_symlink() or dst.exists():
        dst.unlink()
    try:
        os.link(src, dst)
        counts["linked"] += 1
    except OSError as exc:
        if exc.errno != errno.EXDEV:
            raise
        if not warned["cross_device"]:
            print(
                f"warning: {src} and {dst} are on different devices; "
                "copying instead of hard-linking",
                file=sys.stderr,
            )
            warned["cross_device"] = True
        shutil.copy2(src, dst)
        counts["copied"] += 1


def main():
    args = parse_args()

    if not TITLEID_RE.match(args.game):
        fail(f"--game must be a 16-character hex title ID, got {args.game!r}")
    if not APP_RE.match(args.app):
        fail(f"--app must match {APP_RE.pattern}, got {args.app!r}")
    title = " ".join(args.title.split())
    if not title:
        fail("--title must not be empty")

    data = args.data.resolve()
    if not data.is_dir():
        fail(f"data pack is not a folder: {data}")

    host = (args.host or REPO_ROOT / "nxnative" / "dm" / "linux" / "out"
            / args.game.upper() / "dmhost")
    host = host.resolve()
    if not host.is_file():
        fail(f"dmhost not found: {host}")

    out = args.out.resolve()
    if out == data or data in out.parents:
        fail("--out must not be the data pack folder or inside it")
    if out.exists() and not out.is_dir():
        fail(f"--out exists and is not a folder: {out}")

    top_level_names = {p.name for p in data.iterdir()}
    if args.app in top_level_names | {"bin", "save", "temp", "game.json"}:
        fail(f"--app {args.app!r} collides with a reserved or packaged name")

    out.mkdir(parents=True, exist_ok=True)

    counts = {"linked": 0, "copied": 0, "dirs": 0}
    warned = {"cross_device": False}
    for dirpath, dirnames, filenames in os.walk(data):
        rel = Path(dirpath).relative_to(data)
        (out / rel).mkdir(parents=True, exist_ok=True)
        counts["dirs"] += 1
        for name in filenames:
            link_or_copy(Path(dirpath) / name, out / rel / name, counts, warned)

    bin_dir = out / "bin"
    bin_dir.mkdir(exist_ok=True)
    host_dst = bin_dir / "dmhost"
    if host_dst.exists() or host_dst.is_symlink():
        host_dst.unlink()
    shutil.copy2(host, host_dst)
    host_dst.chmod(0o755)

    (out / "save").mkdir(exist_ok=True)
    (out / "temp").mkdir(exist_ok=True)

    logo = args.logo.resolve() if args.logo else data / "logo.png"
    has_logo = logo.is_file()
    if args.logo and not has_logo:
        fail(f"--logo not found: {logo}")
    if has_logo and (out / "logo.png").resolve() != logo:
        shutil.copy2(logo, out / "logo.png")

    launcher = out / args.app
    launcher.write_text(LAUNCHER_TEMPLATE.format(title=title.replace("\n", " ")))
    launcher.chmod(0o755)

    game_json = {
        "command": [str(launcher.resolve())],
        "environment": {},
        "runtime": "native",
        "title": title,
    }
    if has_logo:
        game_json["icon"] = "logo.png"
    with open(out / "game.json", "w", encoding="utf-8") as fh:
        json.dump(game_json, fh, indent=2)
        fh.write("\n")

    print(f"Packaged {title} ({args.game.upper()}) into {out}")
    print(f"  data files hard-linked: {counts['linked']}")
    if counts["copied"]:
        print(f"  data files copied (cross-device): {counts['copied']}")
    print(f"  directories recreated: {counts['dirs']}")
    print(f"  host: {host} -> {host_dst}")
    print("  created: save/, temp/")
    print(f"  launcher: {launcher}")
    print(f"  menu entry: {out / 'game.json'}")
    if not has_logo:
        print("  note: no logo.png (pass --logo with one); game.json has no icon")


if __name__ == "__main__":
    main()
